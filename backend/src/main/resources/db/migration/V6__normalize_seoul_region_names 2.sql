--  V4 는 서울 25개 구를 '서울특별시 / 서울특별시 종로구' 로 넣었고,
--  V5 는 API 응답(estateAgentSggNm) 기준이라 '서울 / 서울 종로구' 입니다.
--  V5 의 ON CONFLICT DO NOTHING 때문에 서울만 옛 표기로 남아
--  화면 필터에서 서울만 다른 형식으로 보입니다.
--
--  크롤러가 지오코딩 주소를 "sido + sigungu + 읍면동 + 지번" 으로 조립하므로
--  표기가 흔들리면 좌표 변환 정확도에도 영향을 줍니다. API 표기로 맞춥니다.
-- ============================================================

UPDATE regions
SET sido        = '서울',
    sigungu     = replace(sigungu, '서울특별시 ', ''),
    region_name = '서울 ' || replace(sigungu, '서울특별시 ', '')
WHERE sido = '서울특별시';
