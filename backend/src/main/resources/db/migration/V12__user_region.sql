-- ============================================================
--  회원 거주 지역
--
--  왜 필요한가
--    수집된 청년정책 404건 중 386건(95%)이 지자체 한정이다.
--    거주지를 모르면 "울산 청년 월세지원" 을 서울 사람에게도 추천하게 되고,
--    맞춤 분석의 결론이 전부 "신청해 볼 만합니다" 로 같아진다.
--
--  REST API 명세서 v4 §3.1 의 signup 요청에도 region 이 있었다.
--  와이어프레임 온보딩 화면에 없어서 빠져 있었으나, 매칭 품질이 이것 하나에 달려 있어
--  단계를 추가한다. (와이어프레임도 함께 수정 필요)
-- ============================================================

ALTER TABLE users ADD COLUMN region VARCHAR(30);

CREATE INDEX idx_users_region ON users (region);

COMMENT ON COLUMN users.region IS '거주 시·도 (서울/부산/…/제주). 지자체 정책 매칭에 사용';

-- 이미 가입한 계정은 지역이 없다. 화면에서 다시 묻되, 시드 계정은 분포를 채워둔다.
UPDATE users
SET region = (ARRAY['서울','경기','부산','대구','인천','광주','대전','울산',
                    '세종','강원','충북','충남','전북','전남','경북','경남','제주'])
             [1 + (id % 17)]
WHERE login_id LIKE 'seed_user_%';

-- 데모 계정은 정책이 가장 많은 지역으로 둬야 시연에서 결과가 보인다.
UPDATE users SET region = '서울' WHERE login_id = 'demo_user';
