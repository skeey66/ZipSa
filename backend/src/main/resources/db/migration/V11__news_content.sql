--  ⚠️ 이 컬럼은 "배포하지 않는 학내 프로젝트" 라는 전제로 추가했습니다.
--     기사 본문은 언론사 저작물입니다. 서비스를 외부에 공개하거나
--     본문을 그대로 보여주는 화면을 배포한다면, 이 컬럼을 비우고
--     제목·요약·원문 링크만 쓰는 방식(V8 상태)으로 되돌려야 합니다.
--
--  본문은 AI 요약과 「나에게 어떻게 적용되나」 판단의 입력으로 씁니다.
--  요약을 만들 때마다 원문을 다시 받지 않도록 한 번만 저장합니다.
-- ============================================================

ALTER TABLE news ADD COLUMN content TEXT;

COMMENT ON COLUMN news.content IS
    '기사 본문. 언론사 저작물 — 외부 배포 시 제거 대상. AI 요약의 입력으로만 사용';
