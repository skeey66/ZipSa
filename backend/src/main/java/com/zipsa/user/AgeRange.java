package com.zipsa.user;

/**
 * 회원가입 온보딩 1단계. 명세 v4 §1.3 과 일치시킨다.
 *
 * 와이어프레임 03 화면의 선택지는 20~30대 4개지만, 명세는 10대와 40대 이상을 포함한다.
 * 화면에서 고를 수 없는 값이라도 enum 에는 둔다 — 나중에 선택지를 넓힐 때
 * 이미 저장된 데이터를 건드리지 않아도 되고, 정책 대상 조건 매칭에도 쓰인다.
 */
public enum AgeRange {
    AGE_10S,        // 10대
    AGE_20S_EARLY,  // 20대 초반 (20~24세)
    AGE_20S_LATE,   // 20대 후반 (25~29세)
    AGE_30S_EARLY,  // 30대 초반 (30~34세)
    AGE_30S_LATE,   // 30대 후반 (35~39세)
    AGE_40S_OVER    // 40대 이상
}
